-- Intermediário: consolida despesas de todos os portais via union all.
-- Para adicionar novo portal: incluir novo CTE + union all abaixo.
-- fonte: 'exercicio' para despesas do orçamento corrente, 'restos_a_pagar' para RAP.

with porciuncula_exercicio as (
    select
        'porciuncula_prefeitura' as portal_slug,
        'exercicio' as fonte,
        ano,
        empresa_id,
        empenho_id,
        pk_empenho,
        pk_empenho_pai,
        tipo_empenho,
        orgao_codigo,
        funcao,
        funcao_nome,
        subfuncao,
        subfuncao_nome,
        elemento,
        natureza_despesa,
        natureza_despesa_codigo,
        categoria,
        grupo_natureza,
        modalidade,
        programa,
        programa_nome,
        proj_atividade,
        projeto_atividade_nome,
        mes,
        fornecedor_nome,
        fornecedor_cpf_cnpj,
        fornecedor_raw,
        licitacao_numero,
        licitacao_modalidade,
        licitacao_descricao,
        fongrupo,
        fongrupo_desc,
        foncodigo,
        foncodigo_desc,
        fonro,
        fonro_desc,
        fonte_stn,
        fonte_stn_desc,
        fonte_recurso_desc,
        data_empenho,
        empenhado,
        liquidado,
        pago,
        dotacao_inicial,
        alteracao_dotacao,
        dotacao_atualizada,
        anulado,
        reforco,
        descricao,
        entidade_nome,
        proc,
        codlo,
        cfpro,
        ficha,
        codif,
        codigo,
        produ,
        vingrupo_vincodigo,
        vincodigonome
    from {{ ref('stg_porciuncula_prefeitura__despesas_gerais') }}
),

porciuncula_fornecedores_perfil_codigo as (
    select distinct on (codif)
        codif as fornecedor_codigo,
        {{ target.schema }}.unaccent(lower(trim(fornecedor_nome))) as fornecedor_nome_clean,
        fornecedor_nome,
        fornecedor_cpf_cnpj,
        natureza_despesa_codigo,
        elemento,
        funcao,
        subfuncao
    from {{ ref('stg_porciuncula_prefeitura__despesas_gerais') }}
    where codif is not null
    order by codif, ano desc, data_empenho desc
),

porciuncula_fornecedores_perfil_nome as (
    select distinct on ({{ target.schema }}.unaccent(lower(trim(fornecedor_nome))))
        codif as fornecedor_codigo,
        {{ target.schema }}.unaccent(lower(trim(fornecedor_nome))) as fornecedor_nome_clean,
        fornecedor_nome,
        fornecedor_cpf_cnpj,
        natureza_despesa_codigo,
        elemento,
        funcao,
        subfuncao
    from {{ ref('stg_porciuncula_prefeitura__despesas_gerais') }}
    where fornecedor_nome is not null
    order by {{ target.schema }}.unaccent(lower(trim(fornecedor_nome))), ano desc, data_empenho desc
),

porciuncula_rap as (
    select
        'porciuncula_prefeitura' as portal_slug,
        'restos_a_pagar' as fonte,
        r.ano,
        r.empresa_id,
        r.rap_id as empenho_id,
        null as pk_empenho,
        null as pk_empenho_pai,
        null as tipo_empenho,
        null as orgao_codigo,
        coalesce(fc.funcao, fn.funcao) as funcao,
        null as funcao_nome,
        coalesce(fc.subfuncao, fn.subfuncao) as subfuncao,
        null as subfuncao_nome,
        coalesce(fc.elemento, fn.elemento) as elemento,
        null as natureza_despesa,
        coalesce(fc.natureza_despesa_codigo, fn.natureza_despesa_codigo) as natureza_despesa_codigo,
        null as categoria,
        null as grupo_natureza,
        null as modalidade,
        null as programa,
        null as programa_nome,
        null as proj_atividade,
        null as projeto_atividade_nome,
        null as mes,
        coalesce(fc.fornecedor_nome, fn.fornecedor_nome, nullif(trim(r.descricao), '')) as fornecedor_nome,
        coalesce(fc.fornecedor_cpf_cnpj, fn.fornecedor_cpf_cnpj) as fornecedor_cpf_cnpj,
        nullif(trim(r.descricao), '') as fornecedor_raw,
        null as licitacao_numero,
        null as licitacao_modalidade,
        null as licitacao_descricao,
        null as fongrupo,
        null as fongrupo_desc,
        null as foncodigo,
        null as foncodigo_desc,
        null as fonro,
        null as fonro_desc,
        null as fonte_stn,
        null as fonte_stn_desc,
        null as fonte_recurso_desc,
        null::date as data_empenho,
        r.empenhado,
        r.liquidado,
        r.pago,
        null::numeric as dotacao_inicial,
        null::numeric as alteracao_dotacao,
        null::numeric as dotacao_atualizada,
        null::numeric as anulado,
        null::numeric as reforco,
        r.descricao,
        null as entidade_nome,
        null as proc,
        null as codlo,
        null as cfpro,
        null as ficha,
        coalesce(r.fornecedor_codigo, fc.fornecedor_codigo) as codif,
        null as codigo,
        null as produ,
        null as vingrupo_vincodigo,
        null as vincodigonome
    from {{ ref('stg_porciuncula_prefeitura__despesas_restos_pagar') }} r
    left join porciuncula_fornecedores_perfil_codigo fc
        on r.fornecedor_codigo = fc.fornecedor_codigo
    left join porciuncula_fornecedores_perfil_nome fn
        on {{ target.schema }}.unaccent(lower(trim(r.descricao))) = fn.fornecedor_nome_clean
),

unificado as (
    select
        portal_slug,
        fonte,
        ano,
        empresa_id,
        empenho_id,
        pk_empenho,
        pk_empenho_pai,
        tipo_empenho,
        orgao_codigo,
        funcao,
        funcao_nome,
        subfuncao,
        subfuncao_nome,
        elemento,
        natureza_despesa,
        natureza_despesa_codigo,
        categoria,
        grupo_natureza,
        modalidade,
        programa,
        programa_nome,
        proj_atividade,
        projeto_atividade_nome,
        mes,
        fornecedor_nome,
        fornecedor_cpf_cnpj,
        fornecedor_raw,
        licitacao_numero,
        licitacao_modalidade,
        licitacao_descricao,
        fongrupo,
        fongrupo_desc,
        foncodigo,
        foncodigo_desc,
        fonro,
        fonro_desc,
        fonte_stn,
        fonte_stn_desc,
        fonte_recurso_desc,
        data_empenho,
        empenhado,
        liquidado,
        pago,
        dotacao_inicial,
        alteracao_dotacao,
        dotacao_atualizada,
        anulado,
        reforco,
        descricao,
        entidade_nome,
        proc,
        codlo,
        cfpro,
        ficha,
        codif,
        codigo,
        produ,
        vingrupo_vincodigo,
        vincodigonome
    from porciuncula_exercicio
    union all
    select
        portal_slug,
        fonte,
        ano,
        empresa_id,
        empenho_id,
        pk_empenho,
        pk_empenho_pai,
        tipo_empenho,
        orgao_codigo,
        funcao,
        funcao_nome,
        subfuncao,
        subfuncao_nome,
        elemento,
        natureza_despesa,
        natureza_despesa_codigo,
        categoria,
        grupo_natureza,
        modalidade,
        programa,
        programa_nome,
        proj_atividade,
        projeto_atividade_nome,
        mes,
        fornecedor_nome,
        fornecedor_cpf_cnpj,
        fornecedor_raw,
        licitacao_numero,
        licitacao_modalidade,
        licitacao_descricao,
        fongrupo,
        fongrupo_desc,
        foncodigo,
        foncodigo_desc,
        fonro,
        fonro_desc,
        fonte_stn,
        fonte_stn_desc,
        fonte_recurso_desc,
        data_empenho,
        empenhado,
        liquidado,
        pago,
        dotacao_inicial,
        alteracao_dotacao,
        dotacao_atualizada,
        anulado,
        reforco,
        descricao,
        entidade_nome,
        proc,
        codlo,
        cfpro,
        ficha,
        codif,
        codigo,
        produ,
        vingrupo_vincodigo,
        vincodigonome
    from porciuncula_rap
)

select
    u.*,
    {{ target.schema }}.unaccent(lower(coalesce(nullif(u.produ, ''), u.descricao, ''))) as texto_objeto,
    {{ target.schema }}.unaccent(lower(coalesce(u.fornecedor_nome, ''))) as texto_fornecedor,
    {{ target.schema }}.unaccent(lower(coalesce(u.fornecedor_nome, '') || ' ' || coalesce(nullif(u.produ, ''), u.descricao, ''))) as texto_completo,
    {{ target.schema }}.unaccent(lower(coalesce(u.projeto_atividade_nome, ''))) as texto_proj_ativ
from unificado u

